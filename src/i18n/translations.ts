export function formatCurrencyWan(amountWan: number, lang: Language): string {
  const abs = Math.abs(amountWan);
  const sign = amountWan < 0 ? '-' : '';
  if (lang === 'en') {
    const dollarsM = abs / 100; // 100 萬 = 1M, 10,000 萬 = 100M, 100,000 萬 = 1B
    if (dollarsM >= 1000) return `${sign}$${(dollarsM / 1000).toFixed(2)}B`;
    if (dollarsM >= 1) return `${sign}$${dollarsM.toFixed(1)}M`;
    return `${sign}$${Math.round(abs * 10)}K`;
  }
  const yi = lang === 'zh-Hans' ? '亿元' : '億元';
  const wan = lang === 'zh-Hans' ? '万元' : '萬元';
  if (abs >= 10000) {
    return `${sign}${(abs / 10000).toFixed(2)} ${yi}`;
  }
  return `${sign}${Math.round(abs).toLocaleString()} ${wan}`;
}

export function formatPop(pop: number, lang: Language): string {
  if (lang === 'en') {
    if (pop >= 1000000) return `${(pop / 1000000).toFixed(2)}M`;
    return `${Math.round(pop / 1000)}K`;
  }
  const unit = lang === 'zh-Hans' ? '万' : '萬';
  return `${Math.round(pop / 10000).toLocaleString()} ${unit}`;
}

export function formatRidershipWan(riders: number, lang: Language): string {
  if (lang === 'en') {
    if (riders >= 1000000) return `${(riders / 1000000).toFixed(2)}M`;
    if (riders >= 1000) return `${(riders / 1000).toFixed(1)}K`;
    return `${Math.round(riders)}`;
  }
  const unit = lang === 'zh-Hans' ? '万' : '萬';
  if (riders >= 10000) return `${(riders / 10000).toFixed(1)} ${unit}`;
  return `${Math.round(riders).toLocaleString()}`;
}

